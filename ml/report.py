"""Render report.md from the result dict written to metrics.json (no recomputation).

Every sentence about "beats", "is worse than" or "no demonstrable difference" is generated by
`ml.eval.verdict` from the numbers. Nothing here chooses words by hand.
"""

from __future__ import annotations

from typing import Any

NO_POSITIVES = "undefined: no positives"
POSITIVE_METRICS = ("pr_auc", "roc_auc", "recall", "f1", "precision")
KIND_TITLE = {"event": "Event target", "regression": "Regression target"}


def md_table(headers: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def num(value: Any, nd: int = 3) -> str:
    return "undefined" if value is None else f"{value:.{nd}f}"


def cell(metric: dict[str, Any] | None, nd: int = 3, no_positives: bool = False) -> str:
    if metric is None:
        return "n/a"
    if metric["value"] is None:
        return NO_POSITIVES if no_positives else "undefined"
    if metric["lo"] is None or metric["hi"] is None:
        return f"{metric['value']:.{nd}f} [CI undefined]"
    return f"{metric['value']:.{nd}f} [{metric['lo']:.{nd}f}, {metric['hi']:.{nd}f}]"


def diff_cell(d: dict[str, Any] | None, nd: int = 3) -> str:
    if d is None:
        return "n/a"
    if d["diff"] is None or d["lo"] is None:
        return "undefined"
    return f"{d['diff']:+.{nd}f} [{d['lo']:+.{nd}f}, {d['hi']:+.{nd}f}]"


VERDICT_WORDS = {
    "beats": "beats",
    "worse": "is worse than",
    "no_difference": "no demonstrable difference",
    "undefined": "undefined",
}


def _flag(result: dict[str, Any], res: dict[str, Any], key: str) -> str:
    if "@" not in key:
        return "baseline"
    set_name = key.split("@", 1)[1]
    return "yes" if res["feature_availability"][set_name]["deployable"] else "NO (diagnostic)"


def target_title(result: dict[str, Any], kind: str) -> str:
    t = result["target"]
    if kind == "event":
        return f"event {t['channel']} >= {t['event_threshold']} {t.get('unit', '')}".strip()
    transform = t.get("regression", {}).get("transform", "none")
    return f"regression of {t['channel']} ({t.get('unit', '')}), fitted on the {transform} scale"


def _top_lines(result: dict[str, Any], kind: str) -> list[str]:
    res = result["targets"][kind]
    lab = res["labels"]
    event = kind == "event"
    role = "Primary" if kind == result["primary_target"] else "Secondary"
    out = [f"### {role} target: {target_title(result, kind)}", ""]
    per_station = ", ".join(f"{s}: {n}" for s, n in lab["per_station"].items())
    pos = (
        f", {lab['positives']} positives" if event else f", {lab['labels_censored']} left-censored"
    )
    out.append(
        f"- Labels used: {lab['labels_used']} on {lab['distinct_dates']} distinct dates{pos} "
        f"({per_station})."
    )
    if event:
        out.append(
            f"- Censored labels: {lab['event_censored_safe_negatives']} left-censored at or below "
            f"the threshold counted as negatives; {lab['event_unknown_censored_dropped']} "
            f"left-censored above the threshold dropped (unknown); "
            f"{result['frame']['target_right_censored_dropped']} right-censored dropped."
        )
    else:
        out.append(
            f"- Censored labels: left-censored values enter at detection limit x "
            f"{result['target'].get('left_censored_factor', 0.5)}; "
            f"{result['frame']['target_right_censored_dropped']} right-censored dropped."
        )
    folds = res["folds"]
    wf = res["walk_forward"]
    if folds and wf:
        n_tr = [f["n_train"] for f in folds]
        pos_tr = (
            f" (training positives {min(f['train_positives'] for f in folds)} to "
            f"{max(f['train_positives'] for f in folds)})"
            if event
            else ""
        )
        pos_te = f", {wf['all']['positives']} positives" if event else ""
        out.append(
            f"- Walk-forward: {len(folds)} folds (test years {folds[0]['fold']} to "
            f"{folds[-1]['fold']}), n_train from {min(n_tr)} to {max(n_tr)}{pos_tr}, "
            f"n_test = {wf['all']['n']} on {wf['all']['n_dates']} dates{pos_te}."
        )
    else:
        out.append("- Walk-forward: NOT evaluated, every fold was skipped (see Warnings).")
    hold = res["holdout_fold"]
    if hold:
        pos = (
            f", {hold['test_positives']} positives; training positives {hold['train_positives']}"
            if event
            else ""
        )
        out.append(
            f"- Final hold-out (evaluated once, last {res['holdout_dates']} distinct dates, from "
            f"{res['holdout_start']}): n_train = {hold['n_train']}, n_holdout = {hold['n_test']}"
            f"{pos}."
        )
    else:
        out.append(f"- Final hold-out: NOT evaluated ({res.get('holdout_skipped') or 'none'}).")
    for name, text in res["baseline_meaning"].items():
        out.append(f"- **{name.replace('_', ' ').capitalize()}** means: {text}.")
    headline = result["headline_feature_set"]
    out.append(
        f"- Verdicts, walk-forward, headline feature set `{headline}` "
        f"({_flag(result, res, 'x@' + headline).replace('yes', 'deployable')}):"
    )
    out += _verdict_lines(res, wf, headline, kind) if wf else ["  - not evaluated."]
    if res["holdout"]:
        out.append(f"- Verdicts, final hold-out, headline feature set `{headline}`:")
        out += _verdict_lines(res, res["holdout"], headline, kind)
    return out


def _verdict_lines(res, block, headline: str, kind: str) -> list[str]:
    lines = []
    wanted = ("persistence", "seasonal_climatology")
    for d in block["all"]["differences"]:
        model, base = d["model"], d["baseline"]
        is_headline_model = model.endswith(f"@{headline}")
        is_clim_vs_pers = model == "seasonal_climatology" and base == "persistence"
        if base not in wanted or not (is_headline_model or is_clim_vs_pers):
            continue
        extra = ""
        if kind == "event" and d.get("brier"):
            b = d["brier"]
            extra = f"; Brier difference {diff_cell(b)} (lower is better)"
        lines.append(f"  - {d['sentence']}{extra}.")
    return lines or ["  - no comparison available."]


def _metrics_tables(result, res, block, kind: str) -> list[str]:
    out: list[str] = []
    scope = block["all"]
    no_pos = kind == "event" and scope.get("positives") == 0
    preds = scope["predictors"]
    if kind == "event":
        out.append(
            f"n = {scope['n']} on {scope['n_dates']} dates, {scope['positives']} positives, "
            f"base rate {num(scope['base_rate'])}. Baselines first, then models. "
            "Brackets: 90% bootstrap CI over distinct dates."
        )
        out.append("")
        rows = []
        for key, e in preds.items():
            m = e["metrics"]
            rows.append(
                [
                    key,
                    _flag(result, res, key),
                    cell(m["pr_auc"], no_positives=no_pos),
                    cell(m["roc_auc"], no_positives=no_pos),
                    cell(m["brier"]),
                    cell(m.get("brier_skill_vs_base_rate")),
                ]
            )
        headers = [
            "predictor",
            "deployable",
            "PR-AUC",
            "ROC-AUC",
            "Brier",
            "Brier skill vs base rate",
        ]
        out += [md_table(headers, rows), ""]
        for label, thr in scope.get("thresholds", {}).items():
            what = "p = 0.5" if label == "0.5" else f"p* = {thr:.2f} (C_FP=1, C_FN=9, PLACEHOLDER)"
            rows = []
            for key, e in preds.items():
                m, c = e["metrics"], e["confusion"][label]
                rows.append(
                    [
                        key,
                        cell(m[f"precision@{label}"]),
                        cell(m[f"recall@{label}"], no_positives=no_pos),
                        cell(m[f"f1@{label}"]),
                        c["tp"],
                        c["fp"],
                        c["fn"],
                        c["tn"],
                    ]
                )
            out += [
                f"At {what}:",
                "",
                md_table(["predictor", "precision", "recall", "F1", "TP", "FP", "FN", "TN"], rows),
                "",
            ]
    else:
        for title, sub in (
            ("All labels", scope),
            ("Numeric-only (uncensored) labels", block["numeric_only"]),
        ):
            unit = result["target"].get("unit", "")
            out.append(
                f"{title}: n = {sub['n']} on {sub['n_dates']} dates"
                f" ({sub.get('n_censored', 0)} left-censored). MAE and RMSE in {unit}. "
                "Brackets: 90% bootstrap CI over distinct dates."
            )
            out.append("")
            rows = []
            for key, e in sub["predictors"].items():
                m = e["metrics"]
                rows.append(
                    [
                        key,
                        _flag(result, res, key),
                        cell(m["mae"]),
                        cell(m["rmse"]),
                        cell(m["r2"]),
                        cell(m["mae_log"]),
                        cell(m.get("skill_vs_persistence")),
                        cell(m.get("skill_vs_seasonal_climatology")),
                    ]
                )
            headers = [
                "predictor",
                "deployable",
                "MAE",
                "RMSE",
                "R2",
                "MAE (log scale)",
                "skill vs persistence",
                "skill vs climatology",
            ]
            out += [md_table(headers, rows), ""]
    primary = "pr_auc" if kind == "event" else "mae"
    name = "PR-AUC" if kind == "event" else "MAE"
    headers = ["model", "baseline", f"{name} difference (model - baseline)"]
    if kind == "event":
        headers.append("Brier difference")
    headers.append("verdict (by " + name + ")")
    rows = []
    for d in scope["differences"]:
        row = [d["model"], d["baseline"], diff_cell(d[primary])]
        if kind == "event":
            row.append(diff_cell(d.get("brier")))
        row.append(VERDICT_WORDS[d["verdict"]])
        rows.append(row)
    better = (
        "higher PR-AUC and lower Brier are better" if kind == "event" else "lower MAE is better"
    )
    out += [f"Paired differences ({better}):", "", md_table(headers, rows), ""]
    return out


def _slice_tables(result, res, block, kind: str) -> list[str]:
    out: list[str] = []
    for name, sub in block["slices"].items():
        if sub["n"] == 0:
            out += [f"**{name}**: no labels.", ""]
            continue
        if kind == "event":
            no_pos = sub["positives"] == 0
            head = f"**{name}**: n = {sub['n']}, positives = {sub['positives']}"
            if no_pos:
                head += f" ({NO_POSITIVES})"
            out += [head, ""]
            rows = [
                [
                    key,
                    cell(e["metrics"]["pr_auc"], no_positives=no_pos),
                    cell(e["metrics"]["roc_auc"], no_positives=no_pos),
                    cell(e["metrics"]["brier"]),
                    cell(e["metrics"]["recall@p*"], no_positives=no_pos)
                    if "recall@p*" in e["metrics"]
                    else "n/a",
                ]
                for key, e in sub["predictors"].items()
            ]
            out += [md_table(["predictor", "PR-AUC", "ROC-AUC", "Brier", "recall at p*"], rows), ""]
        else:
            out += [f"**{name}**: n = {sub['n']} ({sub.get('n_censored', 0)} left-censored)", ""]
            rows = [
                [
                    key,
                    cell(e["metrics"]["mae"]),
                    cell(e["metrics"]["mae_log"]),
                    cell(e["metrics"].get("skill_vs_persistence")),
                    cell(e["metrics"].get("skill_vs_seasonal_climatology")),
                ]
                for key, e in sub["predictors"].items()
            ]
            headers = [
                "predictor",
                "MAE",
                "MAE (log scale)",
                "skill vs persistence",
                "skill vs climatology",
            ]
            out += [md_table(headers, rows), ""]
    return out


def _fold_lines(res, kind: str) -> list[str]:
    if not res["folds"]:
        return []
    event = kind == "event"
    headers = ["fold", "n_train", "n_test", "last train date", "first test date", "last test date"]
    if event:
        headers += ["train positives", "test positives"]
    rows = []
    for f in [*res["folds"], *([res["holdout_fold"]] if res["holdout_fold"] else [])]:
        row = [
            f["fold"],
            f["n_train"],
            f["n_test"],
            f["train_last_date"],
            f["test_first_date"],
            f["test_last_date"],
        ]
        if event:
            row += [f["train_positives"], f["test_positives"] or f"0 ({NO_POSITIVES})"]
        rows.append(row)
    return ["Folds:", "", md_table(headers, rows), ""]


def _leakage(result, res, kind: str) -> list[str]:
    lk = res["leakage_checks"]
    out = [f"### {KIND_TITLE[kind]}", ""]
    out.append("(a) Truncation: features rebuilt with every later row removed.")
    out.append("")
    for t in lk["truncation"]:
        status = (
            "PASS" if t["passed"] else f"FAIL ({t['dates_with_mismatch']} dates) LEAKAGE SUSPECTED"
        )
        out.append(
            f"- `{t['feature_set']}`: {status}; {t['issue_dates_checked']} issue dates, "
            f"{t['rows_checked']} rows compared."
        )
    out.append("")
    sh = lk["shuffled_labels"]
    if sh.get("ran"):
        rule = (
            "suspected when the mean exceeds the base rate by more than "
            f"{sh['margin']:.2f} (PLACEHOLDER)"
            if kind == "event"
            else "suspected when the mean MAE skill against the training mean exceeds "
            f"{sh['margin']:.2f} (PLACEHOLDER)"
        )
        out.append(
            f"(b) Shuffled training labels, {len(sh['seeds'])} repeats (seeds {sh['seeds']}), "
            f"scored on the {sh['n']} real walk-forward labels. {sh['metric']}; reference = "
            f"{sh['reference_name']} = {sh['reference']:.3f}; {rule}."
        )
        out.append("")
        event = kind == "event"
        rows = []
        for key, p in sh["predictors"].items():
            row = [key, f"{p['mean']:.3f}", ", ".join(f"{v:.3f}" for v in p["per_seed"])]
            if event:
                row.append(num(p.get("mean_roc_auc")))
            row.append("LEAKAGE SUSPECTED" if p["suspected"] else "ok")
            rows.append(row)
        headers = ["model", "mean", "per seed"]
        if event:
            headers.append("mean ROC-AUC (no skill = 0.5)")
        out += [md_table([*headers, "result"], rows), ""]
        if event and sh.get("label_blind_expected_pr_auc") is not None:
            out += [
                "Context for reading a flag (not part of the rule): on these "
                f"{sh['n']} labels a ranking that ignores the labels has an expected PR-AUC of "
                f"{sh['label_blind_expected_pr_auc']:.3f} (base rate {sh['reference']:.3f}; "
                "PR-AUC is biased upward on small samples), and a shuffled-label model without "
                "leakage has a mean ROC-AUC near 0.5.",
                "",
            ]
    else:
        out += [f"(b) Shuffled training labels: not run ({sh.get('reason')}).", ""]
    out += [f"(c) Leaky-feature guard: {lk['leaky_feature_guard']}.", ""]
    demo = lk["random_split_demo"]
    if demo.get("ran"):
        wf = res["walk_forward"]
        metric = "pr_auc" if kind == "event" else "mae_log"
        out.append(
            f"(d) {demo['label']}. Random {demo['n_splits']}-fold over the {demo['n']} labels "
            f"before the hold-out, {demo['metric']}:"
        )
        out.append("")
        rows = []
        for key, value in demo["predictors"].items():
            honest = wf["all"]["predictors"][key]["metrics"][metric]["value"] if wf else None
            rows.append([key, f"{value:.3f}", num(honest)])
        out += [md_table(["model", "random split (NOT valid)", "walk-forward (valid)"], rows), ""]
    else:
        out += [f"(d) Random-split demo: not run ({demo.get('reason')}).", ""]
    return out


def _availability(result) -> list[str]:
    out = []
    for kind, res in result["targets"].items():
        rows = []
        for name, av in res["feature_availability"].items():
            years = " and ".join(str(y) for y in av["recent_years"])
            worst = sorted(av["missing_share_by_feature"].items(), key=lambda kv: -kv[1])[:4]
            rows.append(
                [
                    name,
                    "yes" if av["deployable"] else "NO (diagnostic)",
                    len(av["columns"]),
                    f"{av['complete_share']:.0%} of {av['n']}",
                    f"{av['recent_complete_share']:.0%} of {av['recent_n']} ({years})",
                    ", ".join(f"{k} {v:.0%}" for k, v in worst) or "none",
                ]
            )
        headers = [
            "feature set",
            "deployable",
            "columns",
            "complete cases, all labels",
            "complete cases, last two calendar years",
            "most-missing features (share missing)",
        ]
        out += [f"### {KIND_TITLE[kind]}", "", md_table(headers, rows), ""]
    out.append(
        "Missing values are imputed with the training-fold median inside each fold, with a "
        "missing-indicator column. Same-visit measurements are same-date readings (a nowcast)."
    )
    out.append("")
    return out


def _importance(result) -> list[str]:
    out = []
    headline = result["headline_feature_set"]
    for kind, res in result["targets"].items():
        imp = res.get("importance")
        if not imp:
            continue
        keys = [k for k in imp["predictors"] if k.endswith(f"@{headline}")]
        if not keys:
            continue
        feats = sorted(imp["predictors"][keys[0]], key=lambda f: -imp["predictors"][keys[0]][f])
        rows = [[f, *[f"{imp['predictors'][k][f]:+.3f}" for k in keys]] for f in feats]
        out += [
            f"### {KIND_TITLE[kind]} (`{headline}`)",
            "",
            imp["method"] + ". Positive = the model relies on the feature. "
            "Other feature sets are in metrics.json.",
            "",
            md_table(["feature", *keys], rows),
            "",
        ]
    return out


def _conformal(res, unit: str) -> list[str]:
    conf = res.get("conformal")
    if not conf:
        return []
    out = [
        f"Intervals: {conf['method']}, level {conf['level']:.0%}, from {conf['n_residuals']} "
        "residuals, applied to the hold-out predictions."
    ]
    if conf["too_few_residuals"]:
        out.append(
            f"NOTE: fewer than {conf['min_residuals']} residuals; "
            "these intervals are not meaningful."
        )
    out.append("")
    rows = []
    for key, e in conf["predictors"].items():
        if not e:
            continue
        cov = e.get("holdout_coverage")
        rows.append(
            [
                key,
                num(e.get("half_width_transformed"))
                if e.get("half_width_transformed") is not None
                else "infinite",
                "undefined" if cov is None else f"{cov:.0%}",
                num(e.get("holdout_median_width")),
            ]
        )
    if rows:
        headers = [
            "model",
            "half-width (transformed scale)",
            "hold-out coverage",
            f"median width ({unit})",
        ]
        out += [md_table(headers, rows), ""]
    return out


def _reference(result) -> list[str]:
    ref = result.get("reference_comparison")
    if not ref:
        return []
    out = [
        "## Reference comparison",
        "",
        f"Sanity range, not a target ({ref['note']}). Nothing is tuned to match. This run keeps a "
        "final hold-out out of the walk-forward folds, so its test years stop earlier.",
        "",
    ]
    rows = []
    for r in ref["rows"]:
        within = (
            "n/a" if r["within_tolerance"] is None else ("yes" if r["within_tolerance"] else "NO")
        )
        rows.append(
            [
                r["target"],
                r["metric"],
                r["predictor"],
                f"{r['reference']:.3f}",
                num(r["this_run_walk_forward"]),
                "n/a" if r["difference"] is None else f"{r['difference']:+.3f}",
                (within + (" (must check)" if r["must_be_within_tolerance"] else ""))
                if r["target"] == "event"
                else "n/a (ug/L, not a 0 to 1 scale)",
            ]
        )
    headers = [
        "target",
        "metric",
        "predictor",
        "reference probe",
        "this run (walk-forward)",
        "difference",
        f"within {ref['tolerance']:.2f}",
    ]
    out += [md_table(headers, rows), ""]
    return out


def _what_it_shows(result) -> list[str]:
    kind = result["primary_target"]
    res = result["targets"][kind]
    wf = res["walk_forward"]
    hold = res["holdout_fold"]
    parts = []
    if wf:
        parts.append(
            f"This shows how each predictor scored on {wf['all']['n']} out-of-sample "
            f"{result['source']} labels (walk-forward, test years {res['folds'][0]['fold']} to "
            f"{res['folds'][-1]['fold']}) when given readings from the same visit: a nowcast of "
            "the sample-date value, not a forecast for a later date."
        )
    else:
        parts.append("No walk-forward fold could be scored, so this report shows no model skill.")
    parts.append(
        "A model is said to beat a baseline only where the 90% interval of the paired "
        "difference excludes zero; the verdict lines at the top state the outcome for each "
        "baseline, and the same sentence form is used for every outcome."
    )
    parts.append(
        "Seasonal climatology knows only the calendar month. A model that shows no demonstrable "
        "difference from it has not been shown to know more than the season."
    )
    if hold:
        extra = f" with {hold['test_positives']} positives" if kind == "event" else ""
        parts.append(
            f"The final hold-out has {hold['n_test']} labels{extra} and was evaluated once; its "
            "intervals are wide and it cannot settle a close comparison."
        )
    parts.append(
        "It does not show river performance of our own nodes: the inputs are CRP field and lab "
        "readings, not sensor data, and many recent rows have no field readings (see Feature "
        "availability). Feature sets marked NO (diagnostic) use a lab value from the same visit "
        "and say nothing about what a node could do. No hyperparameter was tuned, no result was "
        "used to choose a setting, and real and simulated data are not mixed."
    )
    return ["## What this does and does not show", "", " ".join(parts), ""]


def render_report(result: dict[str, Any], figures: list[str] | None = None) -> str:
    fast = result["fast"]
    out = [f"# Report: {result['task']}" + (" (FAST)" if fast else ""), ""]
    if fast:
        out += [
            "> **FAST run: development only.** Fewer trees and bootstrap resamples. "
            "Do not quote these numbers.",
            "",
        ]
    out += [
        f"Real grab-sample data, `source={result['source']}` only, labels from {result['start']}; "
        f"`quality='good'` rows only. Input `{result['input']['path']}` "
        f"(SHA-256 `{result['input']['sha256'][:16]}...`). Stations: "
        f"{', '.join(result['frame']['stations'])}.",
        "",
        result["description"],
        "",
    ]
    for note in result.get("notes", []):
        out += [f"> Note: {note}", ""]
    out += ["## First lines", ""]
    for kind in result["targets"]:
        out += _top_lines(result, kind) + [""]
    out += ["## Warnings", ""]
    out += [f"- WARNING {w}" for w in result["warnings"]] or ["- none"]
    out.append("")
    out += ["## Metrics", ""]
    for kind, res in result["targets"].items():
        out += [f"### {KIND_TITLE[kind]}: {target_title(result, kind)}", ""]
        out += _fold_lines(res, kind)
        for scope, title in (
            ("walk_forward", "Walk-forward"),
            ("holdout", "Final hold-out (evaluated once)"),
        ):
            block = res[scope]
            out += [f"#### {title}", ""]
            if not block:
                out += ["Not evaluated (see Warnings).", ""]
                continue
            out += _metrics_tables(result, res, block, kind)
        if kind == "regression":
            out += _conformal(res, result["target"].get("unit", ""))
    out += ["## Slices", ""]
    for kind, res in result["targets"].items():
        for scope, title in (("walk_forward", "walk-forward"), ("holdout", "final hold-out")):
            block = res[scope]
            if not block:
                continue
            out += [f"### {KIND_TITLE[kind]}, {title}", ""]
            out += _slice_tables(result, res, block, kind)
    out += ["## Leakage checks", ""]
    for kind, res in result["targets"].items():
        out += _leakage(result, res, kind)
    out += ["## Feature availability", ""]
    out += _availability(result)
    out += _reference(result)
    importance = _importance(result)
    if importance:
        out += ["## Permutation importance", ""] + importance
    if figures:
        out += ["## Figures", ""] + [f"![{name}]({name})" for name in figures] + [""]
    out += _what_it_shows(result)
    return "\n".join(out).rstrip() + "\n"
